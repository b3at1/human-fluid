import {test, expect} from '@playwright/test'

test('appearance persists, follows system, and keeps tasks readable', async ({page}, info) => {
  await page.emulateMedia({colorScheme: 'light'})
  const bootstrap = page.waitForResponse(response => response.url().endsWith('/assets/theme-init.js'))
  await page.goto('/')
  expect((await bootstrap).status()).toBe(200)
  const appearance = page.getByRole('combobox', {name: 'Appearance', exact: true})
  await expect(appearance).toHaveValue('system')
  await appearance.selectOption('dark')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  expect(await page.evaluate(() => localStorage.getItem('hf-theme'))).toBe('dark')
  await page.reload()
  await expect(appearance).toHaveValue('dark')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.getByRole('heading', {name: /A little practice/})).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({path: `test-results/theme-home-${info.project.name}.png`, fullPage: true})
  await page.getByRole('button', {name: 'Start training'}).click()
  await expect(page.getByRole('heading', {name: 'Dependency reasoning', exact: true})).toBeVisible()
  await expect(page.getByLabel('Your scratchpad')).toBeVisible()
  await expect(page.getByRole('radio', {name: 'Yes, every course can be completed'})).toBeVisible()
  expect(await page.evaluate(() => getComputedStyle(document.querySelector('.scratchpad')!).backgroundColor)).toBe('rgb(32, 35, 28)')
  expect(await page.evaluate(() => getComputedStyle(document.querySelector('.primary')!).color)).toBe('rgb(25, 27, 22)')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({path: `test-results/theme-exercise-${info.project.name}.png`, fullPage: true})
  await appearance.selectOption('light')
  await page.emulateMedia({colorScheme: 'dark'})
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await appearance.selectOption('system')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.emulateMedia({colorScheme: 'light'})
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
})

test('built SPA serves its theme bootstrap before startup', async ({page}) => {
  await page.emulateMedia({colorScheme: 'dark'})
  const bootstrap = page.waitForResponse(response => response.url().endsWith('/assets/theme-init.js'))
  await page.goto('http://localhost:8000')
  const response = await bootstrap
  expect(response.status()).toBe(200)
  expect(response.headers()['content-type']).toContain('javascript')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.getByRole('heading', {name: /A little practice/})).toBeVisible()
  await page.getByRole('combobox', {name: 'Appearance', exact: true}).selectOption('light')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
})
